    private void tblNotifAncestorAdded(javax.swing.event.AncestorEvent evt) {//GEN-FIRST:event_tblNotifAncestorAdded
        // TODO add your handling code here:
        DefaultTableModel model = new DefaultTableModel();

        model.addColumn("Kode Produk");
        model.addColumn("Nama Barang");
        model.addColumn("Stok");
        model.addColumn("Harga");

        String sql = "SELECT * FROM produk";

        try {
            Connection conn = koneksi.konek();
            Statement st = conn.createStatement();
            ResultSet rs = st.executeQuery(sql);

            while (rs.next()) {
                String kodeProduk = rs.getString("id_produk");
                String namaBarang = rs.getString("nama_produk");
                String stok = rs.getString("stok");
                String harga = rs.getString("harga");

                Object[] baris = {kodeProduk, namaBarang, stok, harga};

                model.addRow(baris);
            }
        } catch (SQLException sQLException) {
            JOptionPane.showMessageDialog(null, "Gagal Mengambil Data!");
        }catch(Exception e){
            JOptionPane.showMessageDialog(null, e.getMessage());
            e.printStackTrace();
        }
        tblNotif.setModel(model);

    }//GEN-LAST:event_tblNotifAncestorAdded


